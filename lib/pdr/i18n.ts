export function pdrText(language: Language): PdrText {
  return language === Language.BS ? bs : en;
}

export function bilingual(label: { en: string; bs: string } | undefined, language: Language): string {
  if (!label) return '';
  return language === Language.BS ? label.bs : label.en;
}

export function formatNumber(value: number | null | undefined, digits = 2, language: Language = Language.EN): string {
  if (value === null || value === undefined || Number.isNaN(value)) return '—';
  return new Intl.NumberFormat(language === Language.BS ? 'bs-BA' : 'en-GB', { maximumFractionDigits: digits, minimumFractionDigits: 0 }).format(value);
}

export function formatMoney(value: number | undefined, currency = 'EUR', language: Language = Language.EN): string {
  if (value === undefined) return '—';
  return new Intl.NumberFormat(language === Language.BS ? 'bs-BA' : 'en-GB', { style: 'currency', currency, maximumFractionDigits: 0 }).format(value);
}
